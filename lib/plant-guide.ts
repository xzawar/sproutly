const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** Rule-based fallback: find a known plant in the name the user typed. */
export function lookupPlant(name: string): PlantProfile | null {
  const text = ` ${norm(name)} `;
  let best: { entry: Entry; score: number } | null = null;
  for (const entry of GUIDE)
    for (const m of entry.match) {
      const key = norm(m);
      const plurals = [`${key}s`, `${key}es`, key.replace(/y$/, "ies")];
      if ([key, ...plurals].some((k) => text.includes(` ${k} `))) {
        const score = key.length;
        if (!best || score > best.score) best = { entry, score };
      }
    }
  if (!best) return null;
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { match, ...profile } = best.entry;
  return profile;
}
