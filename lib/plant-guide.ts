import { z } from "zod";

/** The care profile the AI returns, and the shape of each built-in guide entry. */
export const plantProfileSchema = z.object({
  common_name: z.string(),
  scientific_name: z.string(),
  category: z.string(),
  environment: z.enum(["indoor", "outdoor"]),
  sunlight: z.enum(["Full", "Partial", "Indirect", "Low light"]),
  watering: z.string(),
  fertilizing: z.string(),
  description: z.string(),
  water_every_days: z.number(),
  fertilize_every_days: z.number().nullable(),
});
export type PlantProfile = z.infer<typeof plantProfileSchema>;

/** Clamp model output to what the form and database accept. */
export function tidyProfile(
  p: PlantProfile,
  categories: string[],
): PlantProfile {
  const clip = (s: string, n: number) => s.trim().slice(0, n);
  const category =
    categories.find(
      (c) => c.toLowerCase() === p.category.trim().toLowerCase(),
    ) ?? "";
  const days = (n: number, min: number, max: number) =>
    Math.min(max, Math.max(min, Math.round(Number.isFinite(n) ? n : min)));
  return {
    common_name: clip(p.common_name, 100),
    scientific_name: clip(p.scientific_name, 150),
    category,
    environment: p.environment,
    sunlight: p.sunlight,
    watering: clip(p.watering, 600),
    fertilizing: clip(p.fertilizing, 600),
    description: clip(p.description, 800),
    water_every_days: days(p.water_every_days, 1, 60),
    fertilize_every_days:
      p.fertilize_every_days == null
        ? null
        : days(p.fertilize_every_days, 7, 365),
  };
}

